// Type-check the TypeScript snippets in README.md against the source, so the
// documented usage cannot silently drift from the API. Placeholders used by the
// snippets (your auth layer, UI helpers) are declared in a prelude.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = new URL('../test/fixtures/.readme/', import.meta.url);
const readme = readFileSync(new URL('../README.md', import.meta.url), 'utf8');
const blocks = [...readme.matchAll(/```ts\n([\s\S]*?)```/g)].map((match) => match[1]);
if (blocks.length === 0) throw new Error('no ts snippets found in README.md');

const prelude = `// Generated by scripts/check-readme.mjs. Placeholders for things the snippets assume.
declare const verifiedUserId: string;
declare const body: { requestId: string; input: unknown };
declare function respond(status: number, payload: unknown): void;
declare const currentUser: { uid: string };
declare const auth: { currentUser: { uid: string } | null };
declare function getIdToken(): Promise<string>;
declare function isMounted(): boolean;
declare function show(result: unknown): void;
declare function showError(message: string): void;
declare function showUnknown(requestId: string): void;
declare function showNotSent(reason: string): void;
declare function render(entries: unknown): void;
declare const requestId: string;
`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
blocks.forEach((code, index) => {
    // Hoist imports above the prelude so the file stays a valid module.
    const lines = code.split('\n');
    const imports = lines.filter((line) => line.startsWith('import '));
    const rest = lines.filter((line) => !line.startsWith('import '));
    writeFileSync(new URL(`readme-${index + 1}.ts`, outDir), `${imports.join('\n')}\n${prelude}\n${rest.join('\n')}\nexport {};\n`);
});
execFileSync(process.execPath, [fileURLToPath(new URL('../node_modules/typescript/bin/tsc', import.meta.url)), '-p', 'test/fixtures/tsconfig.readme.json'], {
    cwd: root,
    stdio: 'inherit',
});
console.log(`check-readme: OK (${blocks.length} snippets type-checked)`);
